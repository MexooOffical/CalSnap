export function searchIndianFoods(query: string): DatabaseFoodItem[] {
  if (!query || !query.trim()) {
    return INDIAN_FOOD_DATABASE.slice(0, 30);
  }
  const q = query.toLowerCase().trim();
  return INDIAN_FOOD_DATABASE.filter(
    (item) =>
      item.name.toLowerCase().includes(q) ||
      (item.hindiName && item.hindiName.toLowerCase().includes(q)) ||
      item.category.toLowerCase().includes(q) ||
      (item.regionalOrigin && item.regionalOrigin.toLowerCase().includes(q))
  );
}

